import crypto from "node:crypto";
import fs from "node:fs";
import sodium from "libsodium-wrappers";

/**
 * Step 1+2 of ONDC onboarding: generate our key pairs and write them to bap/.env.keys (gitignored).
 *   - Signing:    ed25519, libsodium format (64-byte private, 32-byte public), base64. Same as the ONDC SDK.
 *   - Encryption: X25519, private = PKCS#8 DER base64, public = SPKI (ASN.1 DER) base64, as the registry expects.
 * Usage: pnpm keys [--force]
 */

const OUT = new URL("../.env.keys", import.meta.url);
if (fs.existsSync(OUT) && !process.argv.includes("--force")) {
  console.error("bap/.env.keys already exists. Keys registered with a registry must not change silently.");
  console.error("Re-run with --force to overwrite (you must then subscribe again).");
  process.exit(1);
}

await sodium.ready;
const sign = sodium.crypto_sign_keypair();
const enc = crypto.generateKeyPairSync("x25519");
const b64 = (u: Uint8Array) => sodium.to_base64(u, sodium.base64_variants.ORIGINAL);

const values = {
  UNIQUE_KEY_ID: `key-${new Date().toISOString().slice(0, 10)}-${crypto.randomBytes(3).toString("hex")}`,
  SIGNING_PUBLIC_KEY: b64(sign.publicKey),
  SIGNING_PRIVATE_KEY: b64(sign.privateKey),
  ENCRYPTION_PUBLIC_KEY: enc.publicKey.export({ format: "der", type: "spki" }).toString("base64"),
  ENCRYPTION_PRIVATE_KEY: enc.privateKey.export({ format: "der", type: "pkcs8" }).toString("base64"),
  REQUEST_ID: crypto.randomUUID(),
};

fs.writeFileSync(
  OUT,
  `# Generated by \`pnpm keys\` on ${new Date().toISOString()}. SECRET: never commit or share the *_PRIVATE_KEY values.\n` +
    Object.entries(values).map(([k, v]) => `${k}=${v}`).join("\n") +
    "\n",
);

console.log("Wrote bap/.env.keys\n");
console.log(`  unique_key_id          ${values.UNIQUE_KEY_ID}`);
console.log(`  signing_public_key     ${values.SIGNING_PUBLIC_KEY}`);
console.log(`  encryption_public_key  ${values.ENCRYPTION_PUBLIC_KEY}`);
console.log(`  request_id             ${values.REQUEST_ID}`);
console.log("\nNext: pnpm dev, then (once, in another terminal) pnpm subscribe --send");
